// Официальные праздники Казахстана (Трудовой кодекс РК). Ключ — 'ММ-ДД', год не важен: даты каждый год одни и те же.
// Курбан айт сюда не входит: его дата каждый год своя (по лунному календарю).
export const OFFICIAL_HOLIDAYS: Record<string, string> = {
    '01-01': 'Новый год',
    '01-02': 'Новый год',
    '01-07': 'Рождество',
    '03-08': 'Женский день',
    '03-21': 'Наурыз',
    '03-22': 'Наурыз',
    '03-23': 'Наурыз',
    '05-01': 'День единства народа',
    '05-07': 'День защитника Отечества',
    '05-09': 'День Победы',
    '07-06': 'День столицы',
    '08-30': 'День Конституции',
    '10-25': 'День Республики',
    '12-16': 'День Независимости',
};

// '2026-10-25' → '10-25'
export function monthDay(date: string): string {
    return date.slice(5);
}

export function officialHoliday(date: string): string | undefined {
    return OFFICIAL_HOLIDAYS[monthDay(date)];
}
