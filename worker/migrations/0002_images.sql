-- Картинки желаний храним прямо в базе D1, а не в хранилище R2.
-- Почему: чтобы включить R2, Cloudflare требует привязать карту, даже на бесплатном тарифе.
-- D1 бесплатно даёт 5 ГБ: это тысячи картинок по 200–500 КБ.
-- name — '<случайное имя>/full.jpg' или '<случайное имя>/thumb.jpg', data — сами байты JPEG (BLOB)
CREATE TABLE images (
    name TEXT PRIMARY KEY,
    data BLOB NOT NULL
);
